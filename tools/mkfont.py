#!/usr/bin/env python3
"""
generate drivers/display/font.c from a system font.

The bootloader's screens are text, and text needs glyphs.  Rather than carry a
blob nobody can trace, this renders printable ASCII out of a TrueType font on
this machine and writes the result out as a C table.

    tools/mkfont.py                 refresh drivers/display/font.c

FreeMono comes from the GNU FreeFont package, which is under the GPL with a
font exception.  The cell size is fixed rather than measured so that the text
grid in console.c and the glyphs here cannot drift apart.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

WIDTH = 6
HEIGHT = 10
FIRST = 0x20
LAST = 0x7E

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "drivers", "display", "font.c")

CANDIDATES = [
    "/usr/share/fonts/truetype/freefont/FreeMono.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
    "/usr/share/fonts/TTF/DejaVuSansMono.ttf",
]

# The size at which FreeMono's cap height lands just inside the cell.
SIZE = 13


def find_font():
    for p in CANDIDATES:
        if os.path.exists(p):
            return p
    sys.exit("no font found; looked for:\n  " + "\n  ".join(CANDIDATES))


def render(path):
    font = ImageFont.truetype(path, SIZE)
    glyphs = []
    for code in range(FIRST, LAST + 1):
        img = Image.new("1", (WIDTH, HEIGHT), 0)
        d = ImageDraw.Draw(img)
        d.text((0, 0), chr(code), fill=1, font=font)
        px = img.load()
        rows = []
        for y in range(HEIGHT):
            b = 0
            for x in range(WIDTH):
                if px[x, y]:
                    b |= 0x80 >> x
            rows.append(b)
        glyphs.append((code, rows))
    return glyphs


def main():
    path = find_font()
    print("mkfont: %s at %dx%d" % (path, WIDTH, HEIGHT))
    glyphs = render(path)

    with open(OUT, "w") as f:
        f.write("""/*
 * font.c - the bootloader's glyphs.
 *
 * Generated by tools/mkfont.py; do not edit.  %s, rendered at %dx%d, one
 * byte per row with the leftmost pixel in the top bit.  ASCII %d to %d.
 */

#include "spl.h"
#include "board.h"
#include "font.h"

const struct font_glyph font_table[] = {
""" % (os.path.basename(path), WIDTH, HEIGHT, FIRST, LAST))

        for code, rows in glyphs:
            body = ", ".join("0x%02x" % r for r in rows)
            f.write('    { %d, { %s } },   /* %r */\n'
                    % (code, body, chr(code)))
        f.write("""};

/*
 * Chars per line on a panel this wide.  The text grid is what decides where
 * the cursor goes and where a newline puts it, so this is the number that
 * matters - the glyph cell is a drawing detail underneath it.
 */
int font_columns(void)
{
    return PANEL_WIDTH / FONT_W;
}

int font_rows(void)
{
    return PANEL_HEIGHT / FONT_H;
}
""")
    print("mkfont: wrote %s (%d glyphs)" % (OUT, len(glyphs)))


if __name__ == "__main__":
    main()